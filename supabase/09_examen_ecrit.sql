alter table public.questions add column if not exists kind text not null default 'bank';
alter table public.quizzes add column if not exists slide_no int;
create unique index if not exists quizzes_slide_no_uidx on public.quizzes (slide_no) where slide_no is not null;
create table if not exists public.written_slides (
  slide_no int primary key check (slide_no between 1 and 12), series text not null,
  quiz_id uuid references public.quizzes(id) on delete set null,
  status text not null default 'soon' check (status in ('soon','available','incomplete')),
  question_count int not null default 0, expected_questions int not null default 25);
create table if not exists public.written_slide_keys (
  slide_no int primary key check (slide_no between 1 and 12), answer_key jsonb not null default '{}'::jsonb, notes text not null default '');
alter table public.written_slides enable row level security; alter table public.written_slide_keys enable row level security;
drop policy if exists "slides: lecture" on public.written_slides; drop policy if exists "slides: admin" on public.written_slides; drop policy if exists "keys: admin" on public.written_slide_keys;
create policy "slides: lecture" on public.written_slides for select to authenticated using (true);
create policy "slides: admin" on public.written_slides for all using (public.is_admin()) with check (public.is_admin());
-- Les corrections ne sont lisibles QUE par l'administrateur (jamais par les élèves)
create policy "keys: admin" on public.written_slide_keys for all using (public.is_admin()) with check (public.is_admin());
-- Réglages d'apparence : l'administrateur peut aussi créer la ligne si elle manque
drop policy if exists "réglages: admin insère" on public.app_settings;
create policy "réglages: admin insère" on public.app_settings for insert with check (public.is_admin());
insert into public.app_settings (id) values (1) on conflict do nothing;

create or replace function public.q_json(q public.questions) returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id',q.id,'text',q.text,'qtype',q.qtype,'autoplay',q.audio_autoplay,
    'image_path',coalesce((select path from public.media where id = q.image_id), q.image_path),
    'audio_path',(select path from public.media where id = q.audio_id),
    'audio_text',(select text_content from public.media where id = q.audio_id),
    'options',(select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'text',o.text) order by o.position),'[]'::jsonb) from public.question_options o where o.question_id = q.id)) $$;

create or replace function public.get_quiz(p_quiz uuid) returns jsonb language plpgsql security definer set search_path = public as $$
declare qz public.quizzes; res jsonb;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  select * into qz from public.quizzes where id = p_quiz and (status = 'published' or public.is_admin());
  if not found then raise exception 'Contenu introuvable ou non publié'; end if;
  select jsonb_build_object('id',qz.id,'kind',qz.kind,'title',qz.title,'intro_text',qz.intro_text,'outro_text',qz.outro_text,'duration_min',qz.duration_min,'pass_score',qz.pass_score,'slide_no',qz.slide_no,
    'intro_audio',(select path from public.media where id = qz.intro_audio_id),'outro_audio',(select path from public.media where id = qz.outro_audio_id),
    'questions', coalesce((select jsonb_agg(public.q_json(q) order by qq.position) from public.quiz_questions qq join public.questions q on q.id = qq.question_id where qq.quiz_id = qz.id),'[]'::jsonb)) into res;
  return res;
end $$;

drop function if exists public.get_error_questions();
create or replace function public.get_error_questions(p_quiz uuid default null) returns jsonb language sql security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.q_json(q)), '[]'::jsonb) from public.questions q where auth.uid() is not null
    and (p_quiz is null or q.id in (select question_id from public.quiz_questions where quiz_id = p_quiz))
    and q.id in (select question_id from (select distinct on (question_id) question_id, is_correct from public.attempt_answers
      where user_id = auth.uid() order by question_id, created_at desc) t where not t.is_correct) $$;
revoke execute on function public.get_error_questions(uuid) from public, anon;
grant execute on function public.get_error_questions(uuid) to authenticated;

create or replace function public.submit_attempt(p_quiz uuid, p_answers jsonb, p_preview boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare qz public.quizzes; q public.questions; sel uuid[]; corr uuid[]; ok boolean; c int := 0; w int := 0; t int; pct int; pas boolean; aid uuid; det jsonb := '[]'::jsonb;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  select * into qz from public.quizzes where id = p_quiz and (status = 'published' or public.is_admin());
  if not found then raise exception 'Contenu introuvable ou non publié'; end if;
  select count(*) into t from public.quiz_questions where quiz_id = p_quiz;
  if not p_preview then insert into public.attempts(user_id, quiz_id, kind, total) values (auth.uid(), p_quiz, qz.kind, t) returning id into aid; end if;
  for q in select qs.* from public.quiz_questions qq join public.questions qs on qs.id = qq.question_id where qq.quiz_id = p_quiz order by qq.position loop
    sel := array(select j::uuid from jsonb_array_elements_text(coalesce((select x->'selected' from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb)) x where x->>'question_id' = q.id::text limit 1),'[]'::jsonb)) j);
    corr := array(select id from public.question_options where question_id = q.id and is_correct);
    ok := (select coalesce(array_agg(x order by x),'{}') from unnest(sel) x) = (select coalesce(array_agg(x order by x),'{}') from unnest(corr) x);
    if ok then c := c + 1; else w := w + 1; end if;
    if not p_preview then insert into public.attempt_answers(user_id, attempt_id, question_id, selected, is_correct) values (auth.uid(), aid, q.id, to_jsonb(sel), ok); end if;
    det := det || jsonb_build_object('question_id',q.id,'text',q.text,'selected',to_jsonb(sel),'correct_ids',to_jsonb(corr),'is_correct',ok,'explanation',q.explanation,
      'image_path',coalesce((select path from public.media where id = q.image_id), q.image_path),
      'options',(select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'text',o.text) order by o.position),'[]'::jsonb) from public.question_options o where o.question_id = q.id));
  end loop;
  pct := case when t = 0 then 0 else round(100.0 * c / t) end;
  pas := case when qz.kind = 'exam' then pct >= qz.pass_score else null end;
  if not p_preview then update public.attempts set score_pct = pct, correct = c, wrong = w, passed = pas where id = aid; end if;
  return jsonb_build_object('score_pct',pct,'correct',c,'wrong',w,'total',t,'passed',pas,'pass_score',qz.pass_score,'details',det);
end $$;

create or replace function public.admin_set_slide_answers(p_quiz uuid, p_answers jsonb, p_expl jsonb default '{}'::jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Réservé à l''administrateur'; end if;
  update public.question_options o set is_correct = coalesce(exists (select 1 from jsonb_array_elements_text(coalesce(p_answers -> (o.question_id::text), '[]'::jsonb)) e where e = o.text), false)
    where o.question_id in (select question_id from public.quiz_questions where quiz_id = p_quiz);
  update public.questions q set explanation = coalesce(p_expl ->> (q.id::text), q.explanation)
    where q.id in (select question_id from public.quiz_questions where quiz_id = p_quiz);
end $$;
revoke execute on function public.admin_set_slide_answers(uuid, jsonb, jsonb) from public, anon;
grant execute on function public.admin_set_slide_answers(uuid, jsonb, jsonb) to authenticated;

